struct Shimmer::State
{
    const Model& model;
    Transforms transform;
    std::array<InputHistory, ORDERS> dry;
    std::array<Pitch, ORDERS - 1> pitch;
    std::array<Voice, BANKS> voices;
    Weights weights{};
    size_t ramp = 0;
    ColorFilter color;
    Block input{};
    std::array<Block, 2> output{};
    size_t pos = 0;
    double phase = 0.0, ratio = 1.0, until = 0.0;
    Sinc down, up;
    Line<64> host;
    std::array<Line<64>, 2> native;
    float time = .5f, tone = .5f, climb = 1.0f, target_climb = 1.0f;

    explicit State(const Model& shared)
        : model(shared) {
        std::array<Counts, ORDERS> capacity{};
        for (size_t a = 0; a < BANKS; ++a) {
            const auto& bank = model.anchors[a];
            include(capacity[0], bank.late);
            for (size_t j = 0; j < bank.orders; ++j) {
                include(capacity[j], bank.early[j]);
            }
            voices[a].prepare(bank);
        }
        for (size_t j = 0; j < ORDERS; ++j) {
            dry[j].prepare(capacity[j]);
        }
    }

    void controls(float new_time, float new_tone, bool snap) noexcept {
        time = std::clamp(new_time, 0.0f, 1.0f);
        tone = std::clamp(new_tone, 0.0f, 1.0f);
        weights = model.weights(time, tone);
        ramp = snap ? 0 : 32;
        constexpr float NINE = .0054f / .417f;
        target_climb = tone < .2f
                           ? tone * NINE / .2f
                           : std::lerp(NINE, 1.0f, std::clamp((tone - .2f) / .3f, 0.0f, 1.0f));
        if (snap) {
            climb = target_climb;
            for (size_t i = 0; i < BANKS; ++i) {
                voices[i].weight = weights[i];
            }
        }
        color.set(model, time, tone, snap);
    }

    void reset() noexcept {
        phase = until = 0.0;
        pos = 0;
        pitch = {};
        host = {};
        native = {};
        output = {};
        color.history = {};
        for (size_t j = 0; j < ORDERS; ++j) {
            dry[j].reset(7 * j);
        }
        for (size_t a = 0; a < BANKS; ++a) {
            voices[a].reset(a);
        }
        controls(time, tone, true);
    }

    void block() noexcept {
        // All twelve settings use these same input octaves, at the same clock phase.
        std::array<Timing, BLOCK> tick{};
        for (auto& t : tick) {
            t = timing(phase);
            phase += CLOCK / RATE;
            if (phase >= 1) {
                phase -= 1;
            }
        }
        for (size_t j = 0; j < ORDERS; ++j) {
            dry[j].push(input, transform);
            if (j + 1 < ORDERS) {
                for (size_t i = 0; i < BLOCK; ++i) {
                    input[i] = pitch[j].read(input[i], tick[i], model.lowpass);
                }
            }
        }
        const float fraction = ramp > 1 ? 1.0f / static_cast<float>(ramp) : 1.0f;
        climb = std::lerp(climb, target_climb, fraction);
        const std::array<float, 4> gains{1.0f, 1.0f, climb, climb * climb};
        output = {};
        for (size_t a = 0; a < BANKS; ++a) {
            auto& voice = voices[a];
            if (voice.weight != 0.0f || weights[a] != 0.0f) {
                const float end = std::lerp(voice.weight, weights[a], fraction);
                voice.render(model.anchors[a], dry, tick, gains, model.lowpass, transform, end,
                             output);
                if (voice.weight == 0.0f) {
                    voice.reset(a);
                }
            }
        }
        if (ramp > 0) {
            --ramp;
        }
        color.run(output);
    }

    void sample(float x, float& a, float& b) noexcept {
        a = output[0][pos];
        b = output[1][pos];
        input[pos++] = x;
        if (pos == BLOCK) {
            pos = 0;
            block();
        }
    }
};

Shimmer::Shimmer() = default;
Shimmer::~Shimmer() = default;

void Shimmer::prepare(double rate) {
    static const Model shared;
    if (!state) {
        state = std::make_unique<State>(shared);
    }
    state->ratio = rate / RATE;
    if (rate != RATE) {
        state->down.design(.97 * std::min(1.0, RATE / rate));
        state->up.design(.97 * std::min(1.0, rate / RATE));
    }
    reset();
}

void Shimmer::reset() noexcept {
    state->reset();
}

void Shimmer::set_controls(float time, float tone) noexcept {
    if (time != state->time || tone != state->tone) {
        state->controls(time, tone, false);
    }
}

void Shimmer::process(float input, float& a, float& b) noexcept {
    auto& s = *state;
    if (s.ratio == 1.0) {
        s.sample(input, a, b);
        return;
    }
    s.host.push(input);
    while (s.until <= 0.0) {
        s.sample(s.down.read(s.host, s.until), a, b);
        s.native[0].push(a);
        s.native[1].push(b);
        s.until += s.ratio;
    }
    const double fraction = std::clamp(1.0 - s.until / s.ratio, 0.0, std::nextafter(1.0, 0.0));
    a = s.up.read(s.native[0], fraction);
    b = s.up.read(s.native[1], fraction);
    s.until -= 1.0;
}

