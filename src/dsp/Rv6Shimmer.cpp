constexpr double RATE = 48000.0;
constexpr double CLOCK = 1.345816;
constexpr double HOP = RATE / (5 * CLOCK);
constexpr size_t BANKS = 12;
constexpr size_t ORDERS = 4;
constexpr size_t GRID = 20;
constexpr size_t COLOR_TAPS = 512;

struct Anchor
{
    float time{}, tone{}, pulse{};
    size_t orders{};
    std::array<float, ORDERS> motion{};
    std::array<Kernel, ORDERS> early;
    Kernel late;
    std::array<Kernel, 3> late_eq;
    std::array<Kernel, 2> room;

    size_t late_orders() const noexcept {
        return orders == 1 ? 1 : 3;
    }
};

using Color = std::array<float, COLOR_TAPS>;
using Weights = std::array<float, BANKS>;

// Only the resource generated by export_shimmer.py reaches this reader. Multibyte
// fields need not be aligned; Qt's endian helpers also handle big-endian hosts.
struct Reader
{
    std::span<const uchar> data;

    const uchar* take(size_t bytes) {
        if (bytes > data.size()) {
            qFatal("Truncated RV-6 Shimmer resource");
        }
        auto* ptr = data.data();
        data = data.subspan(bytes);
        return ptr;
    }

    uint32_t integer() {
        return qFromLittleEndian<uint32_t>(take(4));
    }
    float real() {
        return std::bit_cast<float>(integer());
    }

    void kernel(Kernel& k, Transforms& transform) {
        Buffer taps(integer());
        for (size_t start = 0; start < taps.size(); start += 256) {
            const float scale = real();
            const size_t length = std::min<size_t>(256, taps.size() - start);
            const auto* q = take(2 * length);
            for (size_t i = 0; i < length; ++i) {
                taps[start + i] = scale * qFromLittleEndian<int16_t>(q + 2 * i);
            }
        }
        k.design(taps, transform);
    }
};

struct Model
{
    std::array<Anchor, BANKS> anchors;
    std::array<float, 95> lowpass{};
    std::vector<std::array<unsigned char, 3>> mesh;
    std::vector<Color> colors;

    Model() {
        const QResource resource(QStringLiteral(":/dsp/rv6-shimmer.bin"));
        Reader r{{resource.data(), static_cast<size_t>(resource.size())}};
        if (std::memcmp(r.take(8), "RV6S\1\0\0\0", 8) != 0 || r.integer() != RATE ||
            r.integer() != BANKS) {
            qFatal("Invalid RV-6 Shimmer resource");
        }
        mesh.resize(r.integer());
        if (r.integer() != GRID || r.integer() != COLOR_TAPS || r.integer() != 256) {
            qFatal("Invalid RV-6 Shimmer filter dimensions");
        }
        for (auto& tap : lowpass) {
            tap = r.real();
        }
        for (auto& anchor : anchors) {
            anchor.time = r.real();
            anchor.tone = r.real();
        }
        for (auto& triangle : mesh) {
            std::copy_n(r.take(3), 3, triangle.begin());
        }
        Transforms transform;
        for (auto& a : anchors) {
            a.orders = r.integer();
            if (a.orders != 1 && a.orders != 4) {
                qFatal("Invalid RV-6 Shimmer octave count");
            }
            a.pulse = r.real();
            for (size_t i = 0; i < a.orders; ++i) {
                a.motion[i] = r.real();
            }
            for (size_t i = 0; i < a.orders; ++i) {
                r.kernel(a.early[i], transform);
            }
            r.kernel(a.late, transform);
            for (size_t i = 0; i < a.late_orders(); ++i) {
                r.kernel(a.late_eq[i], transform);
            }
            for (auto& k : a.room) {
                r.kernel(k, transform);
            }
        }
        colors.resize((GRID + 1) * (GRID + 1));
        for (auto& c : colors) {
            for (auto& tap : c) {
                tap = r.real();
            }
        }
        if (!r.data.empty()) {
            qFatal("Invalid RV-6 Shimmer resource length");
        }
    }

    Weights weights(float time, float tone) const noexcept {
        // At Tone 9:00 the measured first octave is 0.162/1.742 of its noon level.
        constexpr float DARK = 0.5f * 0.162f / 1.742f;
        if (tone < 0.2f) {
            tone *= DARK / 0.2f;
        } else if (tone < 0.5f) {
            tone = std::lerp(DARK, 0.5f, (tone - 0.2f) / 0.3f);
        }
        Weights result{};
        for (const auto& tri : mesh) {
            const auto& a = anchors[tri[0]];
            const auto& b = anchors[tri[1]];
            const auto& c = anchors[tri[2]];
            const float x = time - c.time, y = tone - c.tone;
            const float ax = a.time - c.time, ay = a.tone - c.tone;
            const float bx = b.time - c.time, by = b.tone - c.tone;
            const float det = ax * by - ay * bx;
            const float u = (x * by - y * bx) / det;
            const float v = (ax * y - ay * x) / det;
            const float w = 1.0f - u - v;
            if (std::min({u, v, w}) >= -1e-6f) {
                const std::array<float, 3> bary{u, v, w};
                float total = 0.0f;
                for (size_t i = 0; i < 3; ++i) {
                    result[tri[i]] = bary[i] > 1e-6f ? bary[i] : 0.0f;
                    total += result[tri[i]];
                }
                for (auto& weight : result) {
                    weight /= total;
                }
                break;
            }
        }
        return result;
    }

    void color(float time, float tone, Color& result) const noexcept {
        const float x = time * GRID, y = tone * GRID;
        const size_t i = std::min(static_cast<size_t>(x), GRID - 1);
        const size_t j = std::min(static_cast<size_t>(y), GRID - 1);
        const auto ix = j * (GRID + 1) + i;
        for (size_t k = 0; k < COLOR_TAPS; ++k) {
            result[k] =
                std::lerp(std::lerp(colors[ix][k], colors[ix + 1][k], x - static_cast<float>(i)),
                          std::lerp(colors[ix + GRID + 1][k], colors[ix + GRID + 2][k],
                                    x - static_cast<float>(i)),
                          y - static_cast<float>(j));
        }
    }
};

template <size_t N>
struct Line
{
    static_assert(std::has_single_bit(N));
    std::array<float, N> data{};
    size_t write = 0;
    void push(float value) noexcept {
        write = (write + 1) & (N - 1);
        data[write] = value;
    }
    float at(size_t back) const noexcept {
        return data[(write - back) & (N - 1)];
    }
    float read(float delay) const noexcept {
        const auto i = static_cast<size_t>(delay);
        return std::lerp(at(i), at(i + 1), delay - static_cast<float>(i));
    }
};

struct Timing
{
    float pitch_delay, triangle, moving_delay, cosine;
};

Timing timing(double phase) noexcept {
    const double p = -5 * phase - 0.006 * RATE / HOP;
    const double fraction = p - std::floor(p);
    const double angle = 2 * std::numbers::pi * phase;
    return {static_cast<float>(0.006 * RATE + fraction * HOP),
            static_cast<float>(1 - std::abs(2 * fraction - 1)),
            static_cast<float>(0.00125 * RATE * (1.1 + std::sin(angle))),
            static_cast<float>(std::cos(angle))};
}

struct Pitch
{
    // Mirrored FIR history makes the symmetric 95-tap anti-alias filter contiguous.
    std::array<float, 2 * 95> fir{};
    size_t pos = 0;
    Line<8192> delay;
    float read(float input, const Timing& t, const std::array<float, 95>& lowpass) noexcept {
        pos = pos == 0 ? 94 : pos - 1;
        fir[pos] = fir[pos + 95] = input;
        const float* x = fir.data() + pos;
        float v = lowpass[47] * x[47];
        for (size_t i = 0; i < 47; ++i) {
            v += lowpass[i] * (x[i] + x[94 - i]);
        }
        delay.push(v);
        return t.triangle * delay.read(t.pitch_delay);
    }
};

struct Voice
{
    std::array<FilterOutput, ORDERS> early;
    FilterOutput late;
    std::array<FilterOutput, 3> eq;
    std::array<FilterOutput, 2> room;
    std::array<InputHistory, 3> eq_input;
    InputHistory room_input;
    std::array<Line<128>, ORDERS> early_motion;
    Line<128> late_motion;
    std::array<Pitch, 2> tail_pitch;
    float weight = 0.0f;

    void prepare(const Anchor& a) {
        for (size_t j = 0; j < a.orders; ++j) {
            early[j].prepare(a.early[j]);
        }
        late.prepare(a.late);
        for (size_t j = 0; j < a.late_orders(); ++j) {
            eq_input[j].prepare(a.late_eq[j].count);
            eq[j].prepare(a.late_eq[j]);
        }
        Counts length{};
        for (size_t j = 0; j < 2; ++j) {
            include(length, a.room[j]);
            room[j].prepare(a.room[j]);
        }
        room_input.prepare(length);
    }

    void reset(size_t index) noexcept {
        weight = 0.0f;
        for (auto& o : early) {
            o.reset();
        }
        late.reset();
        early_motion = {};
        late_motion = {};
        tail_pitch = {};
        for (size_t j = 0; j < 3; ++j) {
            eq_input[j].reset(index + j);
            eq[j].reset();
        }
        room_input.reset(5 * index + 3);
        for (auto& o : room) {
            o.reset();
        }
    }

    void render(const Anchor& a, const std::array<InputHistory, ORDERS>& dry,
                const std::array<Timing, BLOCK>& tick, const std::array<float, 4>& climb,
                const std::array<float, 95>& lowpass, Transforms& transform, float end,
                std::array<Block, 2>& mix) noexcept {
        // Each early octave gets its own response and moving tap. The long return is
        // modulated before its two octave reads. All paths meet before the A/B filters.
        Block mono{}, path{};
        for (size_t j = 0; j < a.orders; ++j) {
            early[j].run(dry[j], a.early[j], transform, path);
            for (size_t i = 0; i < BLOCK; ++i) {
                auto& line = early_motion[j];
                line.push(path[i]);
                mono[i] +=
                    climb[j] * std::lerp(path[i], line.read(tick[i].moving_delay), a.motion[j]);
            }
        }
        late.run(dry[0], a.late, transform, path);
        for (size_t i = 0; i < BLOCK; ++i) {
            late_motion.push(path[i]);
            path[i] = (0.5f * path[i] + 0.72f * late_motion.read(tick[i].moving_delay)) *
                      (1.0f + a.pulse * tick[i].cosine);
        }
        Block filtered{};
        for (size_t j = 0; j < a.late_orders(); ++j) {
            eq_input[j].push(path, transform);
            eq[j].run(eq_input[j], a.late_eq[j], transform, filtered);
            for (size_t i = 0; i < BLOCK; ++i) {
                mono[i] += climb[j] * filtered[i];
            }
            if (j + 1 < a.late_orders()) {
                for (size_t i = 0; i < BLOCK; ++i) {
                    path[i] = tail_pitch[j].read(path[i], tick[i], lowpass);
                }
            }
        }
        room_input.push(mono, transform);
        // Cross a cell boundary without dropping the old stereo tail on one sample.
        const float step = (end - weight) / BLOCK;
        for (size_t ch = 0; ch < 2; ++ch) {
            room[ch].run(room_input, a.room[ch], transform, path);
            for (size_t i = 0; i < BLOCK; ++i) {
                mix[ch][i] += (weight + step * static_cast<float>(i + 1)) * path[i];
            }
        }
        weight = end;
    }
};

// The correction between measured settings is common to both stereo outputs. Moving
// along the grid interpolates the fitted FIR coefficients; a knob turn slews over 32 blocks.
struct ColorFilter
{
    std::array<std::array<float, COLOR_TAPS + BLOCK>, 2> history{};
    Color current{}, target{}, step{};
    size_t remaining = 0;
    bool identity = true;

    void set(const Model& model, float time, float tone, bool snap) noexcept {
        model.color(time, tone, target);
        remaining = snap ? 0 : 32;
        if (snap) {
            current = target;
        } else {
            for (size_t k = 0; k < COLOR_TAPS; ++k) {
                step[k] = (target[k] - current[k]) / 32;
            }
        }
        identity = target[0] == 1.0f && std::all_of(target.begin() + 1, target.end(), [](float v) {
                       return v == 0.0f;
                   });
    }

    void run(std::array<Block, 2>& audio) noexcept {
        if (remaining != 0 && --remaining == 0) {
            current = target;
        } else if (remaining != 0) {
            for (size_t k = 0; k < COLOR_TAPS; ++k) {
                current[k] += step[k];
            }
        }
        for (size_t ch = 0; ch < 2; ++ch) {
            auto& h = history[ch];
            std::copy(audio[ch].begin(), audio[ch].end(), h.begin() + COLOR_TAPS);
            if (!identity || remaining != 0) {
                audio[ch].fill(0.0f);
                for (size_t k = 0; k < COLOR_TAPS; ++k) {
                    const float* x = h.data() + COLOR_TAPS - k;
                    for (size_t i = 0; i < BLOCK; ++i) {
                        audio[ch][i] += current[k] * x[i];
                    }
                }
            }
            std::copy_n(h.data() + BLOCK, COLOR_TAPS, h.data());
        }
    }
};

// A causal windowed-sinc bridge around the wet path. All captures and clocked reads
// are at 48 kHz. At that rate the bridge is bypassed in both directions.
struct Sinc
{
    static constexpr size_t TAPS = 48, PHASES = 256;
    std::array<std::array<float, TAPS>, PHASES + 1> table{};

    void design(double cutoff) noexcept {
        for (size_t p = 0; p <= PHASES; ++p) {
            double sum = 0.0;
            for (size_t j = 0; j < TAPS; ++j) {
                const double d = static_cast<double>(j) - 24.0 + static_cast<double>(p) / PHASES;
                const double a = std::numbers::pi * d;
                const double window = 0.42 + 0.5 * std::cos(a / 24) + 0.08 * std::cos(a / 12);
                const double v = window * (d == 0.0 ? cutoff : std::sin(a * cutoff) / a);
                table[p][j] = static_cast<float>(v);
                sum += v;
            }
            for (auto& v : table[p]) {
                v /= static_cast<float>(sum);
            }
        }
    }

    float read(const Line<64>& h, double relative) const noexcept {
        const double base = std::floor(relative);
        const auto back = static_cast<size_t>(-base);
        const size_t p = static_cast<size_t>(std::lround((relative - base) * PHASES));
        float result = 0.0f;
        for (size_t j = 0; j < TAPS; ++j) {
            result += h.at(back + j) * table[p][j];
        }
        return result;
    }
};
